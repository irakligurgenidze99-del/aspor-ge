#!/usr/bin/env node
/**
 * Sandbox-only fallback for Prisma migrations using @prisma/schema-engine-wasm.
 *
 * Normal environments (your laptop, CI, Vercel) should use the standard CLI:
 *   npx prisma migrate dev / npx prisma migrate deploy
 * This script exists because the build sandbox could not download the native
 * schema-engine binary from binaries.prisma.sh. It uses the same migration
 * folder format and the same _prisma_migrations table, so both are interchangeable.
 *
 * Usage:
 *   node scripts/prisma-wasm.mjs init-sql   # (re)generate prisma/migrations/0001_init from the schema (pre-release only)
 *   node scripts/prisma-wasm.mjs deploy     # apply pending migrations to DATABASE_URL
 *   node scripts/prisma-wasm.mjs reset      # DROP everything and re-apply (dev/test only)
 */
import fs from 'node:fs';
import path from 'node:path';
import 'dotenv/config';
import { PrismaPg } from '@prisma/adapter-pg';
import { bindMigrationAwareSqlAdapterFactory } from '@prisma/driver-adapter-utils';

const { SchemaEngine } = await import('@prisma/schema-engine-wasm');

const cmd = process.argv[2];
const url = process.env.DATABASE_URL;
if (!url) throw new Error('DATABASE_URL missing');
const root = path.resolve(import.meta.dirname, '..');
const schemaPath = path.join(root, 'prisma/schema.prisma');
const migDir = path.join(root, 'prisma/migrations');
const schema = fs.readFileSync(schemaPath, 'utf8');
const filters = { externalTables: [], externalEnums: [] };

const adapter = bindMigrationAwareSqlAdapterFactory(new PrismaPg({ connectionString: url }));
const engine = await SchemaEngine.new({ datamodels: [['schema.prisma', schema]] }, () => {}, adapter);

function migrationsList() {
  fs.mkdirSync(migDir, { recursive: true });
  const dirs = fs.readdirSync(migDir, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort();
  const lockPath = path.join(migDir, 'migration_lock.toml');
  return {
    baseDir: migDir,
    lockfile: { path: 'migration_lock.toml', content: fs.existsSync(lockPath) ? fs.readFileSync(lockPath, 'utf8') : null },
    shadowDbInitScript: '',
    migrationDirectories: dirs.map((d) => ({
      path: d,
      migrationFile: { path: 'migration.sql', content: { tag: 'ok', value: fs.readFileSync(path.join(migDir, d, 'migration.sql'), 'utf8') } },
    })),
  };
}

if (cmd === 'init-sql') {
  const r = await engine.diff({ from: { tag: 'empty' }, to: { tag: 'schemaDatamodel', files: [{ path: 'schema.prisma', content: schema }] }, script: true, exitCode: null, filters });
  const dir = path.join(migDir, '0001_init');
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'migration.sql'), r.stdout);
  fs.writeFileSync(path.join(migDir, 'migration_lock.toml'), '# Please do not edit this file manually\nprovider = "postgresql"\n');
  console.log('wrote', path.relative(root, dir));
} else if (cmd === 'diff-sql') {
  // node scripts/prisma-wasm.mjs diff-sql <name> <old-schema.prisma>
  const [name, oldPath] = process.argv.slice(3);
  const old = fs.readFileSync(oldPath, 'utf8');
  const r = await engine.diff({ from: { tag: 'schemaDatamodel', files: [{ path: 'schema.prisma', content: old }] }, to: { tag: 'schemaDatamodel', files: [{ path: 'schema.prisma', content: schema }] }, script: true, exitCode: null, filters });
  const dir = path.join(migDir, name);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'migration.sql'), r.stdout);
  console.log('wrote', path.relative(root, dir));
} else if (cmd === 'deploy') {
  const r = await engine.applyMigrations({ migrationsList: migrationsList(), filters });
  console.log('applied:', r.appliedMigrationNames.join(', ') || '(none)');
} else if (cmd === 'reset') {
  await engine.reset({ filter: filters });
  const r = await engine.applyMigrations({ migrationsList: migrationsList(), filters });
  console.log('reset + applied:', r.appliedMigrationNames.join(', '));
} else {
  console.error('unknown command'); process.exit(1);
}
process.exit(0);
